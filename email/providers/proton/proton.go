const providerName = "proton"

type Config struct {
	IMAPAddress string
	SMTPAddress string
	Username    string
	Password    string
	Email       string
	InsecureTLS bool
}

type Provider struct {
	config  Config
	account email.Account
}

func NewFromEnv() (*Provider, error) {
	cfg := Config{
		IMAPAddress: envOr("PROTON_IMAP_ADDRESS", "127.0.0.1:1143"),
		SMTPAddress: envOr("PROTON_SMTP_ADDRESS", "127.0.0.1:1025"),
		Username:    strings.TrimSpace(os.Getenv("PROTON_BRIDGE_USERNAME")),
		Password:    os.Getenv("PROTON_BRIDGE_PASSWORD"),
		Email:       strings.TrimSpace(os.Getenv("PROTON_EMAIL_ADDRESS")),
		InsecureTLS: strings.EqualFold(os.Getenv("PROTON_TLS_SKIP_VERIFY"), "true"),
	}
	if cfg.Username == "" || cfg.Password == "" {
		return nil, fmt.Errorf("PROTON_BRIDGE_USERNAME and PROTON_BRIDGE_PASSWORD are required (use credentials generated by Proton Mail Bridge)")
	}
	if strings.ContainsAny(cfg.Username+cfg.Password, "\r\n") {
		return nil, fmt.Errorf("Bridge username and password must not contain line breaks")
	}
	if cfg.Email == "" {
		return nil, fmt.Errorf("PROTON_EMAIL_ADDRESS is required; set it to the sender address shown in Proton Mail")
	}
	parsedAddress, err := mail.ParseAddress(cfg.Email)
	if err != nil {
		return nil, fmt.Errorf("PROTON_EMAIL_ADDRESS must be a valid email address: %w", err)
	}
	cfg.Email = parsedAddress.Address
	p := &Provider{config: cfg}
	if err := p.check(context.Background()); err != nil {
		return nil, fmt.Errorf("connect to Proton Mail Bridge: %w", err)
	}
	address := cfg.Email
	p.account = email.Account{ID: "proton-" + strings.ToLower(address), Provider: providerName, Address: address, Name: address, Enabled: true}
	return p, nil
}

func envOr(key, fallback string) string {
	if v := strings.TrimSpace(os.Getenv(key)); v != "" {
		return v
	}
	return fallback
}
func (p *Provider) Account() email.Account { return p.account }

// check validates the Bridge connection and credentials during startup.
func (p *Provider) check(ctx context.Context) error {
	c, err := p.connect(ctx)
	if err != nil {
		return err
	}
	defer c.close()
	_, err = c.command(`SELECT "INBOX"`)
	return err
}

// SearchMessages uses IMAP UIDs so that later actions remain stable across
// mailbox changes. The Bridge account credentials are never logged.
func (p *Provider) SearchMessages(ctx context.Context, box email.Mailbox, query string, limit int) ([]email.Message, error) {
	if ctx == nil {
		ctx = context.Background()
	}
	if limit <= 0 {
		return []email.Message{}, nil
	}
	if strings.ContainsAny(query, "\r\n") {
		return nil, fmt.Errorf("search query must not contain line breaks")
	}
	if limit > 1000 {
		limit = 1000
	}
	switch box {
	case email.MailboxSnoozed, email.MailboxPurchases, email.MailboxScheduled, email.MailboxImportant:
		return nil, fmt.Errorf("the %q mailbox is not exposed as a standard Proton Bridge folder", box)
	}
	c, err := p.connect(ctx)
	if err != nil {
		return nil, err
	}
	defer c.close()
	folder := protonFolder(box)
	if _, err = c.command("SELECT " + imapQuote(folder)); err != nil {
		return nil, fmt.Errorf("select %s: %w", folder, err)
	}
	search := "ALL"
	switch box {
	case email.MailboxStarred:
		search = `FLAGGED`
	case email.MailboxDraft:
		search = `DRAFT`
	case email.MailboxImportant:
		search = `KEYWORD $Important`
	case email.MailboxSpam:
		search = `ALL`
	}
	if strings.TrimSpace(query) != "" {
		search += " TEXT " + imapQuote(query)
	}
	resp, err := c.command("UID SEARCH " + search)
	if err != nil {
		return nil, fmt.Errorf("search Proton mailbox: %w", err)
	}
	uids := parseSearchUIDs(resp)
	if len(uids) == 0 {
		return []email.Message{}, nil
	}
	// IMAP SEARCH returns ascending UIDs; newest messages are normally last.
	if len(uids) > limit {
		uids = uids[len(uids)-limit:]
	}
	out := make([]email.Message, 0, len(uids))
	for i := len(uids) - 1; i >= 0; i-- {
		m, fetchErr := c.fetchMessage(uids[i])
		if fetchErr != nil {
			return out, fetchErr
		}
		m.AccountID = p.account.ID
		m.ID = folder + "|" + m.ID
		out = append(out, m)
	}
	return out, nil
}

func (p *Provider) GetMessage(ctx context.Context, id string) (email.Message, error) {
	if ctx == nil {
		ctx = context.Background()
	}
	folder, uid, err := parseMessageID(id)
	if err != nil {
		return email.Message{}, err
	}
	c, err := p.connect(ctx)
	if err != nil {
		return email.Message{}, err
	}
	defer c.close()
	if _, err = c.command("SELECT " + imapQuote(folder)); err != nil {
		return email.Message{}, err
	}
	m, err := c.fetchMessage(uid)
	if err == nil {
		m.AccountID = p.account.ID
		m.ID = folder + "|" + m.ID
	}
	return m, err
}

func (p *Provider) MarkRead(ctx context.Context, id string) error {
	if ctx == nil {
		ctx = context.Background()
	}
	folder, uid, err := parseMessageID(id)
	if err != nil {
		return err
	}
	c, err := p.connect(ctx)
	if err != nil {
		return err
	}
	defer c.close()
	if _, err = c.command("SELECT " + imapQuote(folder)); err != nil {
		return err
	}
	_, err = c.command(fmt.Sprintf("UID STORE %d +FLAGS.SILENT (\\Seen)", uid))
	return err
}

func (p *Provider) Trash(ctx context.Context, id string) error {
	if ctx == nil {
		ctx = context.Background()
	}
	folder, uid, err := parseMessageID(id)
	if err != nil {
		return err
	}
	c, err := p.connect(ctx)
	if err != nil {
		return err
	}
	defer c.close()
	if _, err = c.command("SELECT " + imapQuote(folder)); err != nil {
		return err
	}
	if _, err = c.command(fmt.Sprintf("UID MOVE %d %s", uid, imapQuote("Trash"))); err == nil {
		return nil
	}
	// MOVE is not available on every Bridge/IMAP version. COPY + Deleted is
	// the portable fallback; avoid EXPUNGE because it affects the whole folder.
	if _, err = c.command(fmt.Sprintf("UID COPY %d %s", uid, imapQuote("Trash"))); err != nil {
		return fmt.Errorf("copy message to Trash: %w", err)
	}
	if _, err = c.command(fmt.Sprintf("UID STORE %d +FLAGS.SILENT (\\Deleted)", uid)); err != nil {
		return err
	}
	// Avoid global EXPUNGE: it could permanently remove other messages that
	// were already marked Deleted by a different mail client.
	return nil
}

func (p *Provider) Send(ctx context.Context, to []string, subject, body string) error {
	if ctx == nil {
		ctx = context.Background()
	}
	if len(to) == 0 {
		return fmt.Errorf("at least one recipient is required")
	}
	for _, addr := range to {
		if _, err := mail.ParseAddress(addr); err != nil {
			return fmt.Errorf("invalid recipient %q: %w", addr, err)
		}
	}
	if strings.ContainsAny(subject, "\r\n") {
		return fmt.Errorf("subject must not contain line breaks")
	}
	fromAddress, err := mail.ParseAddress(p.account.Address)
	if err != nil {
		return fmt.Errorf("invalid sender address: %w", err)
	}
	envelopeRecipients := make([]string, 0, len(to))
	for _, recipient := range to {
		parsed, parseErr := mail.ParseAddress(recipient)
		if parseErr != nil {
			return fmt.Errorf("invalid recipient %q: %w", recipient, parseErr)
		}
		envelopeRecipients = append(envelopeRecipients, parsed.Address)
	}
	from := fromAddress.Address
	var msg strings.Builder
	msg.WriteString("From: " + from + "\r\n")
	msg.WriteString("To: " + strings.Join(envelopeRecipients, ", ") + "\r\n")
	msg.WriteString("Subject: " + mime.QEncoding.Encode("utf-8", subject) + "\r\n")
	msg.WriteString("MIME-Version: 1.0\r\nContent-Type: text/plain; charset=UTF-8\r\nContent-Transfer-Encoding: 8bit\r\n\r\n")
	msg.WriteString(strings.ReplaceAll(strings.ReplaceAll(body, "\r\n", "\n"), "\n", "\r\n"))
	return p.smtpSend(ctx, from, envelopeRecipients, []byte(msg.String()))
}

func (p *Provider) Reply(ctx context.Context, messageID, body string) error {
	m, err := p.GetMessage(ctx, messageID)
	if err != nil {
		return err
	}
	addresses, err := mail.ParseAddressList(m.From)
	if err != nil || len(addresses) == 0 {
		return fmt.Errorf("cannot determine reply recipient")
	}
	recipients := make([]string, 0, len(addresses))
	for _, a := range addresses {
		recipients = append(recipients, a.Address)
	}
	subject := strings.TrimSpace(m.Subject)
	if !strings.HasPrefix(strings.ToLower(subject), "re:") {
		subject = "Re: " + subject
	}
	return p.Send(ctx, recipients, subject, body)
}

func (p *Provider) smtpSend(ctx context.Context, from string, to []string, message []byte) error {
	d := net.Dialer{Timeout: 15 * time.Second}
	conn, err := d.DialContext(ctx, "tcp", p.config.SMTPAddress)
	if err != nil {
		return fmt.Errorf("connect SMTP Bridge %s: %w", p.config.SMTPAddress, err)
	}
	defer conn.Close()
	_ = conn.SetDeadline(time.Now().Add(60 * time.Second))
	if deadline, ok := ctx.Deadline(); ok {
		_ = conn.SetDeadline(deadline)
	}
	client, err := smtp.NewClient(conn, hostOnly(p.config.SMTPAddress))
	if err != nil {
		return err
	}
	defer client.Close()
	if ok, _ := client.Extension("STARTTLS"); ok {
		if err := client.StartTLS(p.smtpTLSConfig()); err != nil {
			return fmt.Errorf("SMTP STARTTLS: %w", err)
		}
	} else {
		return fmt.Errorf("SMTP Bridge does not advertise STARTTLS; refusing an unencrypted connection")
	}
	if ok, _ := client.Extension("AUTH"); !ok {
		return fmt.Errorf("SMTP Bridge did not advertise AUTH after STARTTLS")
	}
	auth := smtp.PlainAuth("", p.config.Username, p.config.Password, hostOnly(p.config.SMTPAddress))
	if err := client.Auth(auth); err != nil {
		return fmt.Errorf("SMTP authentication: %w", err)
	}
	if err := client.Mail(from); err != nil {
		return err
	}
	for _, recipient := range to {
		if err := client.Rcpt(recipient); err != nil {
			return err
		}
	}
	w, err := client.Data()
	if err != nil {
		return err
	}
	if _, err = w.Write(message); err != nil {
		_ = w.Close()
		return err
	}
	if err = w.Close(); err != nil {
		return err
	}
	return client.Quit()
}

type imapConn struct {
	conn    net.Conn
	reader  *bufio.Reader
	nextTag int
}

func (p *Provider) connect(ctx context.Context) (*imapConn, error) {
	if ctx == nil {
		ctx = context.Background()
	}
	d := net.Dialer{Timeout: 15 * time.Second}
	raw, err := d.DialContext(ctx, "tcp", p.config.IMAPAddress)
	if err != nil {
		return nil, fmt.Errorf("connect IMAP Bridge %s: %w", p.config.IMAPAddress, err)
	}
	c := &imapConn{conn: raw, reader: bufio.NewReader(raw)}
	_ = raw.SetDeadline(time.Now().Add(60 * time.Second))
	if deadline, ok := ctx.Deadline(); ok {
		_ = raw.SetDeadline(deadline)
	}
	greeting, err := c.readLine()
	if err != nil {
		raw.Close()
		return nil, err
	}
	if !strings.HasPrefix(strings.ToUpper(greeting), "* OK") {
		raw.Close()
		return nil, fmt.Errorf("unexpected IMAP greeting: %s", greeting)
	}
	if _, err := c.command("STARTTLS"); err != nil {
		raw.Close()
		return nil, fmt.Errorf("IMAP STARTTLS: %w", err)
	}
	tlsConn := tls.Client(raw, p.tlsConfig())
	if err := tlsConn.HandshakeContext(ctx); err != nil {
		raw.Close()
		return nil, fmt.Errorf("IMAP TLS handshake: %w", err)
	}
	c.conn, c.reader = tlsConn, bufio.NewReader(tlsConn)
	if _, err := c.command("LOGIN " + imapQuote(p.config.Username) + " " + imapQuote(p.config.Password)); err != nil {
		c.close()
		return nil, fmt.Errorf("IMAP authentication: %w", err)
	}
	return c, nil
}
func (p *Provider) tlsConfig() *tls.Config {
	return &tls.Config{ServerName: hostOnly(p.config.IMAPAddress), MinVersion: tls.VersionTLS12, InsecureSkipVerify: p.config.InsecureTLS}
}
func (p *Provider) smtpTLSConfig() *tls.Config {
	return &tls.Config{ServerName: hostOnly(p.config.SMTPAddress), MinVersion: tls.VersionTLS12, InsecureSkipVerify: p.config.InsecureTLS}
} // #nosec G402 -- Proton Bridge commonly uses a locally generated certificate; disable only on a trusted local Bridge connection.
func hostOnly(address string) string {
	host, _, err := net.SplitHostPort(address)
	if err == nil {
		return host
	}
	return address
}
func (c *imapConn) close() {
	if c == nil || c.conn == nil {
		return
	}
	_, _ = c.command("LOGOUT")
	_ = c.conn.Close()
}
func (c *imapConn) readLine() (string, error) {
	line, err := c.reader.ReadString('\n')
	if err != nil {
		return "", err
	}
	return strings.TrimRight(line, "\r\n"), nil
}
func (c *imapConn) command(command string) (string, error) {
	c.nextTag++
	tag := fmt.Sprintf("P%04d", c.nextTag)
	if _, err := fmt.Fprintf(c.conn, "%s %s\r\n", tag, command); err != nil {
		return "", err
	}
	var response strings.Builder
	for {
		line, err := c.readLine()
		if err != nil {
			return response.String(), err
		}
		response.WriteString(line)
		response.WriteByte('\n')
		// IMAP literals are length-delimited and may contain arbitrary newlines.
		if n, ok := literalLength(line); ok {
			if n > 32*1024*1024 {
				return response.String(), fmt.Errorf("IMAP literal exceeds 32 MiB safety limit")
			}
			buf := make([]byte, n)
			if _, err := io.ReadFull(c.reader, buf); err != nil {
				return response.String(), err
			}
			response.Write(buf)
			continue
		}
		if strings.HasPrefix(line, tag+" ") {
			if !strings.Contains(strings.ToUpper(line), " OK") {
				return response.String(), fmt.Errorf("IMAP command failed: %s", strings.TrimSpace(line))
			}
			return response.String(), nil
		}
	}
}
func literalLength(line string) (int, bool) {
	re := regexp.MustCompile(`\{([0-9]+)\+?\}$`)
	m := re.FindStringSubmatch(strings.TrimSpace(line))
	if len(m) != 2 {
		return 0, false
	}
	n, err := strconv.Atoi(m[1])
	return n, err == nil
}
func imapQuote(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`
}
func parseSearchUIDs(response string) []uint32 {
	re := regexp.MustCompile(`(?im)^\* SEARCH\s*(.*)$`)
	m := re.FindStringSubmatch(response)
	if len(m) < 2 {
		return nil
	}
	var ids []uint32
	for _, v := range strings.Fields(m[1]) {
		n, err := strconv.ParseUint(v, 10, 32)
		if err == nil && n > 0 {
			ids = append(ids, uint32(n))
		}
	}
	return ids
}
func validUID(id string) (uint32, error) {
	n, err := strconv.ParseUint(strings.TrimSpace(id), 10, 32)
	if err != nil || n == 0 {
		return 0, fmt.Errorf("invalid Proton message UID %q", id)
	}
	return uint32(n), nil
}
func parseMessageID(id string) (string, uint32, error) {
	parts := strings.SplitN(id, "|", 2)
	if len(parts) != 2 {
		return "", 0, fmt.Errorf("invalid Proton message reference %q", id)
	}
	uid, err := validUID(parts[1])
	if err != nil {
		return "", 0, err
	}
	return parts[0], uid, nil
}
func protonFolder(box email.Mailbox) string {
	switch box {
	case email.MailboxSent:
		return "Sent"
	case email.MailboxDraft:
		return "Drafts"
	case email.MailboxAllMail:
		return "All Mail"
	case email.MailboxSpam:
		return "Spam"
	case email.MailboxTrash:
		return "Trash"
	case email.MailboxStarred:
		return "INBOX"
	case email.MailboxSnoozed:
		return "Snoozed"
	case email.MailboxPurchases:
		return "INBOX"
	case email.MailboxImportant:
		return "INBOX"
	default:
		return "INBOX"
	}
}
func (c *imapConn) fetchMessage(uid uint32) (email.Message, error) {
	resp, err := c.command(fmt.Sprintf("UID FETCH %d (UID FLAGS INTERNALDATE BODY.PEEK[])", uid))
	if err != nil {
		return email.Message{}, fmt.Errorf("fetch UID %d: %w", uid, err)
	}
	var raw []byte
	if n, ok := literalLengthFromResponse(resp); ok {
		marker := regexp.MustCompile(`(?s)\{[0-9]+\}\n`).FindStringIndex(resp)
		if marker != nil && len(resp) >= marker[1]+n {
			raw = []byte(resp[marker[1] : marker[1]+n])
		}
	}
	if len(raw) == 0 {
		return email.Message{}, fmt.Errorf("IMAP returned no message body for UID %d", uid)
	}
	return parseRFC822(uid, raw, resp)
}
func literalLengthFromResponse(resp string) (int, bool) {
	re := regexp.MustCompile(`\{([0-9]+)\}`)
	m := re.FindStringSubmatch(resp)
	if len(m) != 2 {
		return 0, false
	}
	n, e := strconv.Atoi(m[1])
	return n, e == nil
}
func parseRFC822(uid uint32, raw []byte, meta string) (email.Message, error) {
	msg, err := mail.ReadMessage(bytes.NewReader(raw))
	if err != nil {
		return email.Message{}, fmt.Errorf("parse message UID %d: %w", uid, err)
	}
	out := email.Message{ID: strconv.FormatUint(uint64(uid), 10), Subject: decodeHeader(msg.Header.Get("Subject")), From: msg.Header.Get("From"), BodyText: "", BodyHTML: ""}
	out.To = addressHeader(msg.Header.Get("To"))
	out.CC = addressHeader(msg.Header.Get("Cc"))
	out.BCC = addressHeader(msg.Header.Get("Bcc"))
	out.ThreadID = msg.Header.Get("Message-ID")
	if date, e := msg.Header.Date(); e == nil {
		out.Date = date
	}
	upper := strings.ToUpper(meta)
	out.Read = strings.Contains(upper, "\\SEEN")
	out.Starred = strings.Contains(upper, "\\FLAGGED")
	out.Important = strings.Contains(upper, "$IMPORTANT")
	contentType := msg.Header.Get("Content-Type")
	mediaType, params, _ := mime.ParseMediaType(contentType)
	transfer := msg.Header.Get("Content-Transfer-Encoding")
	body, _ := io.ReadAll(io.LimitReader(msg.Body, 25*1024*1024))
	if !strings.HasPrefix(mediaType, "multipart/") {
		body = []byte(decodeTransfer(body, transfer))
	}
	textBody, htmlBody, attachments := parseMIMEBody(mediaType, params, body)
	out.BodyText, out.BodyHTML, out.Attachments = textBody, htmlBody, attachments
	return out, nil
}
func decodeHeader(s string) string {
	d := new(mime.WordDecoder)
	v, err := d.DecodeHeader(s)
	if err != nil {
		return s
	}
	return v
}
func addressHeader(s string) []string {
	if strings.TrimSpace(s) == "" {
		return nil
	}
	list, err := mail.ParseAddressList(s)
	if err != nil {
		return []string{s}
	}
	out := make([]string, 0, len(list))
	for _, a := range list {
		out = append(out, a.String())
	}
	return out
}
func parseMIMEBody(mediaType string, params map[string]string, body []byte) (string, string, []email.Attachment) {
	var plain, htmlBody string
	var attachments []email.Attachment
	if strings.HasPrefix(mediaType, "multipart/") {
		boundary := params["boundary"]
		if boundary == "" {
			return "", "", nil
		}
		mr := multipart.NewReader(bytes.NewReader(body), boundary)
		for {
			part, err := mr.NextPart()
			if err != nil {
				break
			}
			data, _ := io.ReadAll(io.LimitReader(part, 20*1024*1024))
			mt, p, _ := mime.ParseMediaType(part.Header.Get("Content-Type"))
			disp, dp, _ := mime.ParseMediaType(part.Header.Get("Content-Disposition"))
			transfer := part.Header.Get("Content-Transfer-Encoding")
			filename := part.FileName()
			if filename == "" {
				filename = dp["filename"]
			}
			if filename != "" || strings.EqualFold(disp, "attachment") {
				attachments = append(attachments, email.Attachment{Name: filepath.Base(filename), MimeType: mt, Size: int64(len(data))})
				continue
			}
			if !strings.HasPrefix(mt, "multipart/") {
				data = []byte(decodeTransfer(data, transfer))
			}
			a, h, nested := parseMIMEBody(mt, p, data)
			if plain == "" {
				plain = a
			}
			if htmlBody == "" {
				htmlBody = h
			}
			attachments = append(attachments, nested...)
		}
		return plain, htmlBody, attachments
	}
	if strings.EqualFold(mediaType, "text/html") {
		htmlBody = strings.TrimSpace(string(body))
	} else {
		plain = strings.TrimSpace(string(body))
	}
	return plain, htmlBody, attachments
}
func decodeTransfer(data []byte, encoding string) string {
	var reader io.Reader = bytes.NewReader(data)
	switch strings.ToLower(strings.TrimSpace(encoding)) {
	case "base64":
		reader = base64.NewDecoder(base64.StdEncoding, reader)
	case "quoted-printable":
		reader = quotedprintable.NewReader(reader)
	}
	decoded, err := io.ReadAll(io.LimitReader(reader, 20*1024*1024))
	if err != nil {
		return strings.TrimSpace(string(data))
	}
	return strings.TrimSpace(string(decoded))
}

